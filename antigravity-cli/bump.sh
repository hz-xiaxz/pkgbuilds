#!/usr/bin/env bash
# Rewrite PKGBUILD for the latest Antigravity CLI (agy). Building/installing is left to paru.
# Source is the manifest agy's own auto-updater reads: per-arch tarball URL plus sha512.
# The URL path carries "<version>-<build id>", which becomes pkgver (with - -> _), the
# same scheme as the AUR antigravity-cli, so the two compare cleanly.
set -euo pipefail

cd "$(dirname "$(readlink -f "$0")")"

manifests=https://antigravity-cli-auto-updater-974169037036.us-central1.run.app/manifests
amd64=$(curl -fsSL "$manifests/linux_amd64.json")
arm64=$(curl -fsSL "$manifests/linux_arm64.json")

# -e: fail on a missing key instead of writing "null" into the PKGBUILD
url_x86_64=$(jq -er .url <<<"$amd64")
url_aarch64=$(jq -er .url <<<"$arm64")
sum_x86_64=$(jq -er .sha512 <<<"$amd64")
sum_aarch64=$(jq -er .sha512 <<<"$arm64")

ver=$(cut -d/ -f6 <<<"$url_x86_64")
[[ $ver == "$(cut -d/ -f6 <<<"$url_aarch64")" ]] || { echo "arch manifests disagree" >&2; exit 1; }
[[ $ver =~ ^[0-9.]+-[0-9]+$ ]] || { echo "unexpected version '$ver' in $url_x86_64" >&2; exit 1; }
pkgver=${ver//-/_}

cat >PKGBUILD <<EOF
# Generated by bump.sh from the agy auto-updater manifests — edit bump.sh, not this file.
pkgname=antigravity-cli
pkgver=$pkgver
pkgrel=1
pkgdesc="Google Antigravity CLI (agy)"
arch=('x86_64' 'aarch64')
url="https://antigravity.google/product/antigravity-cli"
license=('LicenseRef-proprietary')
depends=('glibc')
optdepends=('antigravity: sign in and share session state with the desktop app')
provides=('agy')
conflicts=('agy')
options=('!strip' '!debug')
_rel="https://storage.googleapis.com/antigravity-public/antigravity-cli/\${pkgver//_/-}"
source_x86_64=("agy-\$pkgver-x86_64.tar.gz::\$_rel/linux-x64/cli_linux_x64.tar.gz")
source_aarch64=("agy-\$pkgver-aarch64.tar.gz::\$_rel/linux-arm/cli_linux_arm64.tar.gz")
sha512sums_x86_64=('$sum_x86_64')
sha512sums_aarch64=('$sum_aarch64')

package() {
  install -Dm755 "\$srcdir/antigravity" "\$pkgdir/usr/bin/agy"
}
EOF

echo "antigravity-cli -> $pkgver"
